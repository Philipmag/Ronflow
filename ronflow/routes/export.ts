// POST /api/docs/:id/versions/:versionId/restore - Restore a previous version
router.post('/:id/versions/:versionId/restore', async (req: AuthRequest, res) => {
  try {
    const { id, versionId } = req.params;
    const userId = req.user?.id;

    // Get the version to restore
    const versionRecords = await db.select()
      .from(documentVersions)
      .where(eq(documentVersions.id, versionId))
      .limit(1);

    if (versionRecords.length === 0) {
      res.status(404).json({ error: 'Version not found' });
      return;
    }

    const versionToRestore = versionRecords[0];

    // Get steps from the version to restore
    const oldSteps = await db.select()
      .from(steps)
      .where(eq(steps.versionId, versionId))
      .orderBy(steps.order);

    // Create new version with incremented number
    const versions = await db.select()
      .from(documentVersions)
      .where(eq(documentVersions.documentId, id))
      .orderBy(desc(documentVersions.versionNumber))
      .limit(1);

    const latestVersionNumber = versions[0]?.versionNumber || 0;
    const newVersionNumber = latestVersionNumber + 1;

    const newVersion = await db.insert(documentVersions).values({
      id: uuidv4(),
      documentId: id,
      versionNumber: newVersionNumber,
      versionLabel: `Restored from v${versionToRestore.versionNumber}`,
      changeDescription: `Restored from version ${versionToRestore.versionNumber}`,
      createdByUserId: userId || null
    }).returning();

    // Copy steps to new version
    for (const step of oldSteps) {
      await db.insert(steps).values({
        id: uuidv4(),
        documentId: id,
        versionId: newVersion[0].id,
        order: step.order,
        title: step.title,
        description: step.description,
        actionType: step.actionType,
        rawEventMetadata: step.rawEventMetadata,
        screenshotUrl: step.screenshotUrl,
        annotationMetadata: step.annotationMetadata,
        aiGenerated: step.aiGenerated,
        notes: step.notes
      });
    }

    // Update document's current version reference
    await db.update(documents).set({
      currentVersionId: newVersion[0].id,
      updatedAt: new Date()
    }).where(eq(documents.id, id));

    // Log audit event
    await db.insert(auditLogs).values({
      id: uuidv4(),
      orgId: (await db.select({ orgId: documents.orgId }).from(documents).where(eq(documents.id, id)).limit(1))[0].orgId,
      userId: userId || null,
      action: 'document.version.restore',
      entityType: 'document',
      entityId: id,
      metadata: { restoredFrom: versionId, newVersion: newVersion[0].id }
    });

    res.json({
      success: true,
      newVersion: newVersion[0]
    });
  } catch (error) {
    console.error('Restore version error:', error);
    res.status(500).json({ error: 'Failed to restore version' });
  }
});

